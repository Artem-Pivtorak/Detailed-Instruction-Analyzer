const I18nContext = createContext<{ lang: Lang; t: (k: string) => string }>({
  lang: "EN",
  t: (k) => k,
});

export function I18nProvider({
  lang,
  children,
}: {
  lang: Lang;
  children: React.ReactNode;
}) {
  const t = (k: string) => {
    const raw =
      translations[lang] && translations[lang][k] ? translations[lang][k] : k;
    // {YEAR} -> поточний рік (наприклад, в копірайті: 2019-2026, 2019-2027, ...)
    return raw.split("{YEAR}").join(String(new Date().getFullYear()));
  };
  return (
    <I18nContext.Provider value={{ lang, t }}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
